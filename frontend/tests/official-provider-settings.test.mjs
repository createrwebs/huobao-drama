test('settings page offers the supported official provider presets', () => {
  assert.match(providerPresetBlock('text'), /gpt-4o/)
  assert.doesNotMatch(providerPresetBlock('text'), /minimax/i)
  assert.doesNotMatch(providerPresetBlock('image'), /'ali'|minimax/i)
  assert.match(providerPresetBlock('video'), /volcengine/)
  assert.match(providerPresetBlock('video'), /minimax/)
  assert.match(providerPresetBlock('video'), /aliyun/)
  assert.doesNotMatch(providerPresetBlock('video'), /'vidu'/i)
  assert.doesNotMatch(settingsPage, /audio:\s*\{/)
})

test('ToraAPI quick setup delegates config seeding to the server', () => {
  assert.match(scriptContent, /await authAPI\.login\(apiKey\)/)
  assert.match(scriptContent, /await authAPI\.me\(\)/)
  assert.match(scriptContent, /await loadCfgs\(\)/)
  // loginTora function should not create configs manually - aiConfigAPI.create appears later in saveCfg
  const loginStart = scriptContent.indexOf('async function loginTora')
  const logoutStart = scriptContent.indexOf('async function logoutTora')
  const loginSlice = scriptContent.slice(loginStart, logoutStart)
  assert.doesNotMatch(loginSlice, /aiConfigAPI\.create/)
  assert.doesNotMatch(loginSlice, /api\.firemux\.com/)
})
